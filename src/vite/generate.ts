import { dirname, isAbsolute, relative, sep } from "node:path";
import type { RouteEntry, ScanResult } from "./scan";

/**
 * Emits `routeTree.gen.ts`. The text is a pure function of the scan: sorted, LF line endings, no
 * timestamps and no absolute paths, so regenerating an unchanged tree produces identical bytes.
 */

/** The route options a route module can export, in the order the generator writes them. */
const OPTION_EXPORTS = [
  "pending",
  "pendingMs",
  "error",
  "notFound",
  "validateSearch",
  "loaderDeps",
  "matchFilters",
  "beforeLoad",
  "loader",
  "head",
  "tags",
  "staleReload",
  "metadata",
  "generateMetadata",
  "notFoundMetadata",
  "errorMetadata",
  "viewport",
  "generateViewport",
  "links",
  "meta",
  "headers",
] as const;

/**
 * The ids of the routes whose chain runs server middleware: a route that exports `middleware`, a route
 * inside a folder with a `_middleware` file (the routes root contains everything), and every route
 * below one of those (its layouts run in its chain). `scan.entries` is in tree pre-order, so a parent
 * is decided before its children.
 */
function serverGatedIds(scan: ScanResult): Set<string> {
  const folders = (scan.middleware ?? []).map((entry) => entry.folder);
  const gated = new Set<string>();
  for (const entry of scan.entries) {
    const own =
      entry.info.exports.includes("middleware") ||
      folders.some((folder) => folder === "" || entry.file.startsWith(`${folder}/`));
    const inherited = entry.parentId !== undefined && gated.has(entry.parentId);
    if (own || inherited) gated.add(entry.id);
  }
  return gated;
}

/**
 * Exports whose code is loaded lazily by the route-splitting transform.
 *
 * @example
 * import { UI_EXPORTS } from "@shadow-js/router/vite";
 * UI_EXPORTS.includes("pending"); // true
 * @since 1.0.0
 */
export const UI_EXPORTS: readonly string[] = ["default", "pending", "error", "notFound"];

/**
 * The route options that need a router feature, and the feature (its factory and subpath) they need.
 * The generator imports a feature only when a route of the tree exports the option, so a tree without
 * heads, filters, loaders or error components pulls in none of them.
 */
const FEATURE_OF_OPTION: readonly {
  readonly option: string;
  readonly factory: string;
  readonly subpath: string;
}[] = [
  { option: "head", factory: "headManagement", subpath: "head" },
  { option: "error", factory: "errorBoundaries", subpath: "errors" },
  { option: "loader", factory: "loaderCache", subpath: "loaders" },
  { option: "matchFilters", factory: "matchFilters", subpath: "filters" },
];

/** Options of {@link generateRouteTree}. @since 1.0.0 */
export interface GenerateOptions {
  /** Absolute path of the file that will hold the text; imports are relative to its folder. */
  readonly generatedFile: string;
}

function posix(path: string): string {
  return sep === "/" ? path : path.split(sep).join("/");
}

/** Import specifier of a route file as seen from the generated file: relative, no extension. */
function specifierOf(generatedFile: string, absolutePath: string): string {
  const rel = posix(relative(dirname(generatedFile), absolutePath));
  const withoutExtension = rel.replace(/\.(?:tsx|ts|jsx|js|mts|mjs)$/, "");
  return withoutExtension.startsWith(".") ? withoutExtension : `./${withoutExtension}`;
}

function quote(text: string): string {
  return JSON.stringify(text);
}

function postOrder(roots: readonly RouteEntry[]): RouteEntry[] {
  const out: RouteEntry[] = [];
  const stack: { entry: RouteEntry; visited: boolean }[] = [];
  for (let index = roots.length - 1; index >= 0; index -= 1) {
    const root = roots[index];
    if (root !== undefined) stack.push({ entry: root, visited: false });
  }
  while (stack.length > 0) {
    const item = stack.pop();
    if (item === undefined) break;
    if (item.visited) {
      out.push(item.entry);
      continue;
    }
    stack.push({ entry: item.entry, visited: true });
    for (let index = item.entry.children.length - 1; index >= 0; index -= 1) {
      const child = item.entry.children[index];
      if (child !== undefined) stack.push({ entry: child, visited: false });
    }
  }
  return out;
}

const HEADER = [
  "// @generated by @shadow-js/router/vite. Do not edit: this file is rewritten when route files change.",
  "// biome-ignore-all lint: generated file",
  "// biome-ignore-all format: generated file",
  "// biome-ignore-all assist/source/organizeImports: generated file",
  "/* eslint-disable */",
].join("\n");

const PRELOAD_HELPER = `function preloadComponent(component: unknown): Promise<unknown> {
  if (typeof component === "function" && "preload" in component && typeof component.preload === "function") {
    return Promise.resolve(component.preload());
  }
  return Promise.resolve();
}`;

/**
 * Generates the text of `routeTree.gen.ts` for a scan.
 *
 * The file imports every route module by its plain path (so editors and `tsc` see the real
 * module types), builds the route tree with `defineRoute`, exports `routeTree`, `routes` (typed
 * by path), `routeMeta` and `preloadRoutes`, and augments `Register` so that `A`, `navigate`,
 * `useParams`, `useSearch` and `useLoaderData` only accept registered paths.
 *
 * @param scan A successful {@link scanRoutes} result.
 * @param options Where the text will be written.
 * @returns The file text, ending with a newline.
 * @example
 * writeFileSync(file, generateRouteTree(await scanRoutes({ routesDir }), { generatedFile: file }));
 * @since 1.0.0
 */
export function generateRouteTree(scan: ScanResult, options: GenerateOptions): string {
  if (!isAbsolute(options.generatedFile)) {
    throw new TypeError("generateRouteTree: generatedFile must be an absolute path");
  }
  // `defineTemplate` is imported only by a tree that has a template, so any other tree is unchanged.
  const hasTemplate = scan.entries.some((entry) => entry.template === true);
  const lines: string[] = [
    HEADER,
    `import { defineRoute, ${hasTemplate ? "defineTemplate, " : ""}type RouterFeature } from "@shadow-js/router";`,
  ];
  // The features the tree needs, one import each (see FEATURE_OF_OPTION).
  const needed = FEATURE_OF_OPTION.filter((feature) =>
    scan.entries.some((entry) => entry.info.exports.includes(feature.option)),
  );
  for (const feature of needed) {
    lines.push(
      `import { ${feature.factory} } from ${quote(`@shadow-js/router/${feature.subpath}`)};`,
    );
  }
  const names = new Map<string, { module: string; route: string }>();
  scan.entries.forEach((entry, index) => {
    names.set(entry.id, { module: `m${index}`, route: `r${index}` });
  });
  const gated = serverGatedIds(scan);

  for (const entry of scan.entries) {
    const name = names.get(entry.id);
    if (name === undefined) continue;
    lines.push(
      `import * as ${name.module} from ${quote(specifierOf(options.generatedFile, entry.absolutePath))};`,
    );
  }
  lines.push("");

  for (const entry of postOrder(scan.roots)) {
    const name = names.get(entry.id);
    if (name === undefined) continue;
    const props: string[] = [`id: ${quote(entry.id)}`];
    // A template's component is wrapped so that it remounts when the matched path changes.
    if (entry.info.hasDefault) {
      props.push(
        `component: ${entry.template === true ? `defineTemplate(${name.module}.default)` : `${name.module}.default`}`,
      );
    }
    for (const option of OPTION_EXPORTS) {
      if (entry.info.exports.includes(option)) props.push(`${option}: ${name.module}.${option}`);
    }
    // The literal read from the source: the server handler decides how to render from it.
    if (entry.info.config.ssr !== undefined) {
      props.push(`ssr: ${JSON.stringify(entry.info.config.ssr)}`);
    }
    if (entry.info.config.revalidate !== undefined) {
      props.push(`revalidate: ${JSON.stringify(entry.info.config.revalidate)}`);
    }
    if (entry.info.config.cache !== undefined) {
      props.push(`cache: ${JSON.stringify(entry.info.config.cache)}`);
    }
    // The literal read from the source: with `false`, the server answers not found for a param the page's
    // `prerender` export does not list.
    if (entry.info.config.dynamicParams !== undefined) {
      props.push(`dynamicParams: ${JSON.stringify(entry.info.config.dynamicParams)}`);
    }
    // A flag only: the middleware code itself stays out of the generated tree (the browser imports it).
    if (gated.has(entry.id)) props.push("serverMiddleware: true");
    if (entry.children.length > 0) {
      const children = entry.children.map((child) => names.get(child.id)?.route ?? "").join(", ");
      props.push(`children: [${children}]`);
    }
    lines.push(`const ${name.route} = defineRoute(${quote(entry.path)}, {`);
    for (const prop of props) lines.push(`  ${prop},`);
    lines.push("});");
  }
  lines.push("");

  const rootNames = scan.roots.map((root) => names.get(root.id)?.route ?? "");
  lines.push(`export const routeTree = [${rootNames.join(", ")}] as const;`);
  lines.push("");

  lines.push(
    "/** The router features the routes of this tree need: `createRouter({ routes: routeTree, features: routerFeatures })`. */",
  );
  const featureCalls = needed.map((feature) => `${feature.factory}()`);
  lines.push(
    `export const routerFeatures: readonly RouterFeature[] = [${featureCalls.join(", ")}];`,
  );
  lines.push("");

  const endpoints = scan.entries.filter((entry) => entry.isEndpoint);
  lines.push(
    `/** Every route by id: pages by URL pattern, layouts by folder + "/_layout"${hasTemplate ? ', templates by folder + "/_template"' : ""}. */`,
  );
  lines.push("export const routes = {");
  for (const entry of scan.entries) {
    lines.push(`  ${quote(entry.id)}: ${names.get(entry.id)?.route ?? ""},`);
  }
  lines.push("} as const;");
  lines.push("");

  lines.push("/** Static facts about each route, read from its source. */");
  lines.push(
    'export const routeMeta: Readonly<Record<string, { readonly kind: "page" | "layout"; readonly file: string; readonly ssr?: boolean | "data-only"; readonly prerender?: boolean | readonly string[] }>> = {',
  );
  for (const entry of scan.entries) {
    const props = [`kind: ${quote(entry.kind)}`, `file: ${quote(entry.file)}`];
    if (entry.info.config.ssr !== undefined)
      props.push(`ssr: ${JSON.stringify(entry.info.config.ssr)}`);
    if (entry.info.config.prerender !== undefined) {
      props.push(`prerender: ${JSON.stringify(entry.info.config.prerender)}`);
    }
    lines.push(`  ${quote(entry.id)}: { ${props.join(", ")} },`);
  }
  lines.push("};");
  lines.push("");

  lines.push(PRELOAD_HELPER);
  lines.push("");
  lines.push("const lazyComponents: Readonly<Record<string, readonly unknown[]>> = {");
  for (const entry of scan.entries) {
    const name = names.get(entry.id);
    if (name === undefined) continue;
    const components: string[] = [];
    for (const key of UI_EXPORTS) {
      if (entry.info.exports.includes(key)) components.push(`${name.module}.${key}`);
    }
    lines.push(`  ${quote(entry.id)}: [${components.join(", ")}],`);
  }
  lines.push("};");
  lines.push("");
  lines.push("/**");
  lines.push(
    " * Loads the lazily split components of routes (all routes when `ids` is omitted). Await it",
  );
  lines.push(" * before hydrating, so the first client render finds the code the server rendered.");
  lines.push(" */");
  lines.push("export function preloadRoutes(ids?: readonly string[]): Promise<void> {");
  lines.push("  const wanted = ids ?? Object.keys(lazyComponents);");
  lines.push("  const loads: Promise<unknown>[] = [];");
  lines.push("  for (const id of wanted) {");
  lines.push(
    "    for (const component of lazyComponents[id] ?? []) loads.push(preloadComponent(component));",
  );
  lines.push("  }");
  lines.push("  return Promise.all(loads).then(() => undefined);");
  lines.push("}");
  lines.push("");

  lines.push('declare module "@shadow-js/router" {');
  lines.push("  interface Register {");
  if (endpoints.length === 0) {
    lines.push("    paths: string;");
  } else {
    const paths = endpoints.map((entry) => entry.id).sort();
    lines.push(`    paths: ${paths.map(quote).join(" | ")};`);
  }
  lines.push("  }");
  lines.push("}");
  lines.push("");
  return lines.join("\n");
}

/**
 * Generates the source of a module listing the API routes, for the server entry. Each route has
 * its URL pattern, its methods and a lazy `load` that imports the file. It is separate from the
 * route tree on purpose: the tree reaches the browser, API modules must not.
 *
 * @param scan A successful scan.
 * @returns Module text exporting `apiRoutes`.
 * @example
 * generateApiRoutesModule(scan); // export const apiRoutes = [{ id: "/api/health", ... }];
 * @since 1.0.0
 */
export function generateApiRoutesModule(scan: ScanResult): string {
  const lines: string[] = ["export const apiRoutes = ["];
  for (const api of scan.api) {
    const specifier = posix(api.absolutePath);
    lines.push(
      `  { id: ${quote(api.id)}, path: ${quote(api.fullPath)}, methods: ${JSON.stringify(api.methods)}, load: () => import(${quote(specifier)}) },`,
    );
  }
  lines.push("];");
  lines.push("");
  return lines.join("\n");
}
