describe("writeIfChanged", () => {
  it("[FRT-105] writes once, then leaves the file (and its mtime) alone", async () => {
    const tree = makeTree({});
    trees.push(tree);
    const file = join(tree.root, "nested", "routeTree.gen.ts");
    expect(await writeIfChanged(file, "a\n")).toBe(true);
    const old = new Date(2020, 1, 1);
    utimesSync(file, old, old);
    expect(await writeIfChanged(file, "a\n")).toBe(false);
    expect(statSync(file).mtimeMs).toBe(old.getTime());
    expect(await writeIfChanged(file, "b\n")).toBe(true);
    expect(statSync(file).mtimeMs).toBeGreaterThan(old.getTime());
  });

  it("[FRT-106] leaves no temporary file behind, also when the write fails", async () => {
    const tree = makeTree({});
    trees.push(tree);
    const file = join(tree.root, "out.gen.ts");
    await writeIfChanged(file, "x");
    expect(readdirSync(tree.root)).toEqual(["out.gen.ts"]);
    // A directory where the file should be: the rename fails, the temporary file is removed.
    const blocked = join(tree.root, "blocked.gen.ts");
    writeFileSync(join(tree.root, "keep"), "");
    await writeIfChanged(join(tree.root, "dir", "f"), "x");
    await expect(writeIfChanged(join(tree.root, "dir"), "y")).rejects.toThrow();
    expect(existsSync(blocked)).toBe(false);
    expect(readdirSync(tree.root).filter((name) => name.endsWith(".tmp"))).toEqual([]);
  });
});

describe("metadata exports", () => {
  it("[FRT-120] metadata, generateMetadata, viewport, generateViewport, links, meta and headers reach the route options; the router imports no metadata feature", async () => {
    const tree = makeTree({
      "routes/_layout.tsx": `${PAGE}export const metadata = { title: "Root" };\nexport const viewport = { width: "device-width" };`,
      "routes/posts/[id].tsx": `${PAGE}export const generateMetadata = () => ({ title: "Post" });\nexport const generateViewport = () => ({});\nexport const links = [{ rel: "preload", href: "/a.woff2" }];\nexport const meta = () => [];\nexport const headers = () => ({});`,
    });
    trees.push(tree);
    const generatedFile = join(tree.root, "routeTree.gen.ts");
    const text = generateRouteTree(await scanRoutes({ routesDir: join(tree.root, "routes") }), {
      generatedFile,
    });
    for (const option of [
      "metadata",
      "viewport",
      "generateMetadata",
      "generateViewport",
      "links",
      "meta",
      "headers",
    ]) {
      expect(text).toMatch(new RegExp(`${option}: m\\d+\\.${option}`));
    }
    expect(text).not.toContain("metadataFeature");
  });
});
